def simplify(text: str) -> str:
    out = []
    for ch in text:
        out.append(SIMPLIFY.get(ch, ch))
    return "".join(out)

def clean_line(t: str) -> str:
    # 去行内图片编号标注（(见圈X) 等 OCR 垃圾）
    t = re.sub(r'[（(]?\s*见\s*[圈圃固圆画]\s*[一二三四五六七八九十\d]+\s*[）)]?', '', t)
    t = re.sub(r'[（(]\s*\d+\s*[）)]', '', t)
    t = re.sub(r'[\s\u3000]+', '', t)  # 去所有空白（竖排 OCR 每字一空格）
    return t

